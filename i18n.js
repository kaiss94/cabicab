// ── Init ─────────────────────────────────────────────────────
function i18nInit() {
  injectLangSwitcher();
  const lang = getLang();
  applyTranslations(lang);
  updateLangSwitcher(lang);
  document.documentElement.lang = lang;
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', i18nInit);
} else {
  i18nInit();
}
