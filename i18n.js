// ── Langue active ─────────────────────────────────────────────
const SUPPORTED_LANGS = ['fr', 'en', 'es'];
const DEFAULT_LANG = 'fr';

function getLang() {
  return localStorage.getItem('cabicab_lang') || DEFAULT_LANG;
}

function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  localStorage.setItem('cabicab_lang', lang);
  applyTranslations(lang);
  updateLangSwitcher(lang);
  document.documentElement.lang = lang;
}

// Retourne une clé traduite dans la langue active (ou FR par défaut)
function t(key) {
  const lang = getLang();
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key])
      || (TRANSLATIONS[DEFAULT_LANG] && TRANSLATIONS[DEFAULT_LANG][key])
      || key;
}

// Applique toutes les traductions aux éléments data-i18n
function applyTranslations(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS[DEFAULT_LANG];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (dict[key] !== undefined) el.placeholder = dict[key];
  });

  // Mise à jour du title et meta description
  if (dict['meta.title'])       document.title = dict['meta.title'];
  if (dict['meta.description']) {
    const m = document.querySelector('meta[name="description"]');
    if (m) m.setAttribute('content', dict['meta.description']);
  }
}

// Met à jour l'apparence des boutons de langue
function updateLangSwitcher(lang) {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

// Inject le sélecteur de langue dans la nav (appelé une fois au chargement)
function injectLangSwitcher() {
  // Cherche la nav
  const navInner = document.querySelector('.nav-inner');
  if (!navInner || document.querySelector('.lang-switcher')) return;

  const style = document.createElement('style');
  style.textContent = `
    .lang-switcher {
      display: flex; align-items: center; gap: 4px;
      background: rgba(255,255,255,0.08);
      border-radius: 20px;
      padding: 3px 6px;
      margin-right: 6px;
    }
    .lang-btn {
      background: none; border: none; cursor: pointer;
      font-size: 0.75rem; font-weight: 600;
      color: rgba(255,255,255,0.55);
      padding: 3px 7px; border-radius: 14px;
      transition: all .15s;
      font-family: inherit;
      letter-spacing: 0.05em;
    }
    .lang-btn:hover { color: rgba(255,255,255,0.9); }
    .lang-btn.active {
      background: rgba(200,168,90,0.25);
      color: #c8a85a;
    }
  `;
  document.head.appendChild(style);

  const switcher = document.createElement('div');
  switcher.className = 'lang-switcher';
  switcher.innerHTML = `
    <button class="lang-btn" data-lang="fr">FR</button>
    <button class="lang-btn" data-lang="en">EN</button>
    <button class="lang-btn" data-lang="es">ES</button>
  `;
  switcher.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
  });

  // Insérer avant le bouton CTA nav
  const navCta = navInner.querySelector('.nav-cta');
  if (navCta) navInner.insertBefore(switcher, navCta);
  else navInner.appendChild(switcher);
}

// ── Init ─────────────────────────────────────────────────────
function i18nInit() {
  injectLangSwitcher();
  const lang = getLang();
  applyTranslations(lang);
  updateLangSwitcher(lang);
  document.documentElement.lang = lang;
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', i18nInit);
} else {
  i18nInit();
}
