// ── Langue active ─────────────────────────────────────────────
const SUPPORTED_LANGS = ['fr', 'en', 'es', 'it', 'ko', 'zh'];
const DEFAULT_LANG = 'fr';

function getLang() {
  return localStorage.getItem('cabicab_lang') || DEFAULT_LANG;
}

function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  localStorage.setItem('cabicab_lang', lang);
  applyTranslations(lang);
  updateLangSwitcher(lang);
  document.documentElement.lang = lang;
}

// Retourne une clé traduite dans la langue active (ou FR par défaut)
function t(key) {
  const lang = getLang();
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key])
      || (TRANSLATIONS[DEFAULT_LANG] && TRANSLATIONS[DEFAULT_LANG][key])
      || key;
}

// Applique toutes les traductions aux éléments data-i18n
function applyTranslations(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS[DEFAULT_LANG];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (dict[key] !== undefined) el.placeholder = dict[key];
  });

  // Mise à jour du title et meta description
  if (dict['meta.title'])       document.title = dict['meta.title'];
  if (dict['meta.description']) {
    const m = document.querySelector('meta[name="description"]');
    if (m) m.setAttribute('content', dict['meta.description']);
  }
}

// Ouvre/ferme le menu déroulant
function toggleLangMenu() {
  const menu = document.getElementById('langMenu');
  if (menu) menu.classList.toggle('open');
}

// Met à jour l'affichage du dropdown
function updateLangSwitcher(lang) {
  const cur = document.querySelector('.lang-current');
  if (cur) cur.textContent = lang.toUpperCase();
  document.querySelectorAll('.lang-opt').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  const menu = document.getElementById('langMenu');
  if (menu) menu.classList.remove('open');
}

